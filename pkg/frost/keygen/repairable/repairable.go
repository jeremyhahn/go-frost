// Package repairable implements the Repairable Threshold Scheme for FROST.
//
// This allows recovery of a lost share using cooperation of threshold participants,
// without reconstructing the group secret. Based on the paper:
// "A Survey and Refinement of Repairable Threshold Schemes"
// https://eprint.iacr.org/2017/1155
//
// The protocol has three steps:
//
//  1. Step 1 (Each Helper): Generate random delta values that sum to their
//     Lagrange-weighted share contribution for the lost participant.
//
//  2. Step 2 (Each Helper): Sum all received delta values to compute sigma.
//
//  3. Step 3 (Recovering Participant): Sum all sigma values to recover the share.
//
// Security Requirements:
//   - At least 2 helpers are required (the threshold for the original scheme)
//   - Delta values between helpers must be sent on secure channels
//   - Sigma values to the recovering participant must be sent on secure channels
package repairable

import (
	"runtime"

	"github.com/jeremyhahn/go-frost/pkg/frost"
	"github.com/jeremyhahn/go-frost/pkg/frost/ciphersuite"
	"github.com/jeremyhahn/go-frost/pkg/frost/group"
	"github.com/jeremyhahn/go-frost/pkg/frost/helpers"
)

// Step1Result contains the delta values generated by a helper for all other helpers.
type Step1Result struct {
	// Deltas maps each helper's identifier to their delta value.
	// Each helper receives a delta from this helper.
	Deltas map[frost.Identifier]group.Scalar
}

// Zeroize securely erases the delta values from memory.
//
// This method should be called after the delta values have been transmitted
// to reduce the risk of memory disclosure attacks.
func (r *Step1Result) Zeroize() {
	for id, delta := range r.Deltas {
		runtime.KeepAlive(delta)
		if delta != nil {
			bytes := delta.Bytes()
			for i := range bytes {
				bytes[i] = 0
			}
			r.Deltas[id] = delta.Sub(delta)
		}
	}
	for _, delta := range r.Deltas {
		runtime.KeepAlive(delta)
	}
}

// RepairShareStep1 is executed by each helper to generate delta values.
//
// Each helper generates (n-1) random delta values (where n is the number of helpers),
// with the last delta computed to ensure the sum equals their Lagrange-weighted
// contribution to the recovering participant's share.
//
// Inputs:
//   - helperIdentifiers: All helpers participating in the recovery (including self)
//   - myKeyPackage: This helper's key package
//   - participantToRecover: The identifier of the participant whose share is being recovered
//   - suite: The ciphersuite to use
//
// Outputs:
//   - result: Map of delta values, one for each helper (including self)
//
// Errors:
//   - Returns error if fewer than 2 helpers
//   - Returns error if duplicate helper identifiers
//   - Returns error if this helper is not in the helper list
func RepairShareStep1(
	helperIdentifiers []frost.Identifier,
	myKeyPackage *frost.KeyPackage,
	participantToRecover frost.Identifier,
	suite ciphersuite.Ciphersuite,
) (*Step1Result, error) {
	// Validate inputs
	if len(helperIdentifiers) < 2 {
		return nil, frost.NewParameterError("helperIdentifiers", "at least 2 helpers required", frost.ErrInsufficientParticipants)
	}

	if myKeyPackage == nil {
		return nil, frost.NewParameterError("myKeyPackage", "cannot be nil", frost.ErrInvalidParameters)
	}

	// Check for duplicates and verify we're in the list
	seen := make(map[frost.Identifier]bool)
	foundSelf := false
	for _, id := range helperIdentifiers {
		if seen[id] {
			return nil, frost.NewParameterError("helperIdentifiers", "contains duplicates", frost.ErrDuplicateParticipant)
		}
		seen[id] = true
		if id == myKeyPackage.Identifier {
			foundSelf = true
		}
	}

	if !foundSelf {
		return nil, frost.NewParameterError("helperIdentifiers", "must include own identifier", frost.ErrInvalidParticipant)
	}

	grp := suite.Group()

	// Convert helper identifiers to scalars for Lagrange computation
	helperScalars := make([]group.Scalar, len(helperIdentifiers))
	for i, id := range helperIdentifiers {
		scalar, err := helpers.IdentifierToScalar(grp, id)
		if err != nil {
			return nil, frost.NewParticipantError(id, "failed to convert ID to scalar", err)
		}
		helperScalars[i] = scalar
	}

	// Get our scalar
	myScalar, err := helpers.IdentifierToScalar(grp, myKeyPackage.Identifier)
	if err != nil {
		return nil, frost.NewParameterError("myIdentifier", "failed to convert to scalar", err)
	}

	// Convert participant to recover to scalar
	participantScalar, err := helpers.IdentifierToScalar(grp, participantToRecover)
	if err != nil {
		return nil, frost.NewParameterError("participantToRecover", "failed to convert to scalar", err)
	}

	// Compute Lagrange coefficient for this helper at the recovery point
	// zeta_i = L_i(participantToRecover) where L_i is the Lagrange basis polynomial
	lambda, err := computeLagrangeCoefficient(helperScalars, participantScalar, myScalar, grp)
	if err != nil {
		return nil, err
	}

	// Compute our Lagrange-weighted contribution: lambda * myShare
	contribution := lambda.Mul(myKeyPackage.SecretShare)

	// Generate random delta values for all helpers except the last
	// The last delta is computed to make the sum equal to our contribution
	numHelpers := len(helperIdentifiers)
	deltas := make(map[frost.Identifier]group.Scalar)

	// Generate random deltas for first (n-1) helpers
	randomSum := grp.NewScalar() // Accumulate sum of random deltas
	for i := 0; i < numHelpers-1; i++ {
		delta, err := grp.RandomScalar()
		if err != nil {
			return nil, frost.NewParameterError("delta", "failed to generate random delta", err)
		}
		deltas[helperIdentifiers[i]] = delta
		randomSum = randomSum.Add(delta)
	}

	// Last delta = contribution - sum(random deltas)
	lastDelta := contribution.Sub(randomSum)
	deltas[helperIdentifiers[numHelpers-1]] = lastDelta

	return &Step1Result{Deltas: deltas}, nil
}

// RepairShareStep2 is executed by each helper to compute their sigma value.
//
// Each helper sums all the delta values they received (including from themselves)
// to produce a sigma value that will be sent to the recovering participant.
//
// Inputs:
//   - deltas: All delta values received from other helpers (and self)
//
// Outputs:
//   - sigma: The sum of all deltas
func RepairShareStep2(deltas []group.Scalar) group.Scalar {
	if len(deltas) == 0 {
		return nil
	}

	// Sum all deltas (bounds checked above: len(deltas) > 0)
	sigma := deltas[0].Copy()
	for i := 1; i < len(deltas); i++ {
		sigma = sigma.Add(deltas[i]) //nolint:gosec // bounds checked by loop condition
	}

	return sigma
}

// RepairShareStep3 is executed by the recovering participant to compute their share.
//
// The recovering participant sums all sigma values received from helpers
// to recover their signing share.
//
// Inputs:
//   - sigmas: All sigma values received from helpers
//   - identifier: The recovering participant's identifier
//   - commitment: The original VSS commitment (for verification)
//   - suite: The ciphersuite to use
//
// Outputs:
//   - keyPackage: A key package with the recovered share
//
// Errors:
//   - Returns error if verification fails
func RepairShareStep3(
	sigmas []group.Scalar,
	identifier frost.Identifier,
	groupPublicKey group.Element,
	commitment []group.Element,
	suite ciphersuite.Ciphersuite,
) (*frost.KeyPackage, error) {
	if len(sigmas) == 0 {
		return nil, frost.NewParameterError("sigmas", "cannot be empty", frost.ErrInvalidParameters)
	}

	grp := suite.Group()

	// Sum all sigmas to recover the share (bounds checked above: len(sigmas) > 0)
	recoveredShare := sigmas[0].Copy()
	for i := 1; i < len(sigmas); i++ {
		recoveredShare = recoveredShare.Add(sigmas[i]) //nolint:gosec // bounds checked by loop condition
	}

	// Verify the recovered share if commitment is provided
	if len(commitment) > 0 {
		idScalar, err := helpers.IdentifierToScalar(grp, identifier)
		if err != nil {
			return nil, frost.NewParameterError("identifier", "failed to convert to scalar", err)
		}

		// Verify: g^recoveredShare == evaluate_commitment(commitment, identifier)
		left := grp.ScalarBaseMult(recoveredShare)
		right := evaluateCommitmentPolynomial(commitment, idScalar, grp)

		if !left.Equal(right) {
			return nil, frost.NewVerificationError("recoveredShare", "share verification failed", frost.ErrInvalidKeyShare)
		}
	}

	// Create key package with recovered share
	return &frost.KeyPackage{
		Identifier:     identifier,
		SecretShare:    recoveredShare,
		GroupPublicKey: groupPublicKey,
		// VerificationShares would need to be obtained separately
	}, nil
}

// computeLagrangeCoefficient computes the Lagrange coefficient L_i(x)
// for participant i at point x, given all participant identifiers.
//
// L_i(x) = product((x - x_j) / (x_i - x_j)) for all j != i
func computeLagrangeCoefficient(
	xCoords []group.Scalar,
	x group.Scalar,
	xi group.Scalar,
	grp group.Group,
) (group.Scalar, error) {
	polyHelper := helpers.NewPolynomialHelper(grp)

	// Find xi in xCoords
	var xiIndex = -1
	for i, coord := range xCoords {
		if coord.Equal(xi) {
			xiIndex = i
			break
		}
	}

	if xiIndex == -1 {
		return nil, frost.NewParameterError("xi", "not found in xCoords", frost.ErrInvalidParameters)
	}

	// Use the polynomial helper to compute the Lagrange coefficient
	// We need to compute at point x instead of 0
	// L_i(x) = product((x - x_j) / (x_i - x_j)) for all j != i

	// Initialize numerator and denominator to 1
	oneBytes := make([]byte, grp.ScalarLength())
	if grp.ByteOrder() == group.BigEndian {
		oneBytes[len(oneBytes)-1] = 1
	} else {
		oneBytes[0] = 1
	}
	one, _ := grp.DeserializeScalar(oneBytes)
	numerator := one
	denominator := one.Copy()

	for j, xj := range xCoords {
		if j == xiIndex {
			continue
		}

		// numerator *= (x - xj)
		xMinusXj := x.Sub(xj)
		numerator = numerator.Mul(xMinusXj)

		// denominator *= (xi - xj)
		xiMinusXj := xi.Sub(xj)
		denominator = denominator.Mul(xiMinusXj)
	}

	// Result = numerator / denominator = numerator * denominator^(-1)
	denominatorInv, err := denominator.Inv()
	if err != nil {
		return nil, frost.NewParameterError("denominator", "inversion failed", err)
	}

	// If polynomial helper has DeriveInterpolatingValue, we could potentially use it
	// but it computes at x=0. For general x, we need the above computation.
	_ = polyHelper // Used for potential future optimization

	return numerator.Mul(denominatorInv), nil
}

// evaluateCommitmentPolynomial evaluates the commitment polynomial at point x.
// Returns: product(commitment[k]^(x^k)) for k=0..t-1
func evaluateCommitmentPolynomial(commitment []group.Element, x group.Scalar, grp group.Group) group.Element {
	// Start with identity
	result := grp.Identity()

	// Create scalar 1
	oneBytes := make([]byte, grp.ScalarLength())
	if grp.ByteOrder() == group.BigEndian {
		oneBytes[len(oneBytes)-1] = 1
	} else {
		oneBytes[0] = 1
	}
	xPower, _ := grp.DeserializeScalar(oneBytes)

	for _, c := range commitment {
		// Compute commitment[k]^(x^k)
		term := grp.ScalarMult(c, xPower)

		// Add to result
		result = result.Add(term)

		// Update x^k for next iteration
		xPower = xPower.Mul(x)
	}

	return result
}
